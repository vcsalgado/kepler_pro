	--Autor: Victor Salgado
	--Fecha: 23/12/2025
--kdivcl, kddinv
--kdtallcont
--
	--Variables de definicion de documento
	variable_id text = '';
	anio_new integer = 0;
	anio_old integer = 0;

	--Variables de uso general 
	strValor text = '';
	intValor int = 0;
	kdc1_old text = '';
	kdc1_new text = '';
	kdc2_old text = '';
	kdc2_new text = '';
	expSql text ='';
	cont int = 0;
	campo_cargo text='';
	campo_abono text='';
	campo_mes text='';
	anio_inicio text='';
	registro record;
	strval text = '';
	nombre_tabla text = '';
	ultimo_anio text = '';
	nombre_folio text =  '';

	--Variables de retorno
	resultado text;
	mensaje text;
	adicionales text;
begin

	anio_new := 26;
	anio_old :=anio_new-1;


	--Contabilidad kdc1
	kdc1_old :=format('kdc1%1$s',anio_old);
	kdc1_new :=format('kdc1%1$s',anio_new);
	anio_inicio:='24';

	--Creacion KDC1
	expSql:= concat('create table keplersc.',kdc1_new,' (LIKE keplersc.', kdc1_old ,' including all) ');
	raise notice 'Ejecutando: %', expSql;
	execute expSql;
	commit;	

/*
	--Copiar registros a KDC1 
	ALTER TABLE keplersc.kdc125 DISABLE TRIGGER kdc1_upd_nivel_after_crud;
    raise notice 'Copiando registros a %',kdc1_new;
    expSql =concat('insert into keplersc.',kdc1_new,' select *  from keplersc.',kdc1_old);
	raise notice 'Insert %',expSql; 
    execute expSql;
	commit;
*/
	--Generacion de trigger
	expSql:=concat('create trigger kdc1_upd_nivel_after_crud after 
		insert or delete or update on keplersc.',kdc1_new,
		' for each row execute function keplersc.cont_upd_nivel()');
	raise notice 'Ejecutando: %', expSql;
	execute expSql;
	commit;


	--Creacion de KDC2's
	for cont in 1..12 loop
		nombre_tabla:=lpad(cont::text,2,'0');
		nombre_tabla:=concat('kdc2',anio_new::text,nombre_tabla);
		expSql:= concat('create table keplersc.',nombre_tabla,' (like keplersc.kdc2', anio_old,lpad(cont::text,2,'0'), ' including all)');
		raise notice 'Creando: %', expSql;
		execute expSql;
		commit;

		expSql:=concat('create trigger ', nombre_tabla, '_upd_nivel_after_crud after 
			insert or delete or update on keplersc.',nombre_tabla,
			' for each row execute function keplersc.cont_upd_saldos()');
		raise notice 'Copiando: %', expSql;
		execute expSql;
		commit;
	end loop;



	for cont in 1..12 loop
		nombre_tabla:=lpad(cont::text,2,'0');
		nombre_tabla:=concat('kdc2',anio_new::text,nombre_tabla);

		nombre_folio:=lpad(cont::text,2,'0');
		nombre_folio:=concat('POLIZAI',anio_new::text,nombre_folio);
		raise notice 'Creando folio: %', nombre_folio;
		insert into keplersc.sqliov (c1,c4,c5,c6,col_sucursal) values(nombre_folio,'0',nombre_tabla,'c1','00'); 

		nombre_folio:=lpad(cont::text,2,'0');
		nombre_folio:=concat('POLIZAE',anio_new::text,nombre_folio);
		raise notice 'Creando folio: %', nombre_folio;
		insert into keplersc.sqliov (c1,c4,c5,c6,col_sucursal) values(nombre_folio,'0',nombre_tabla,'c1','00'); 

		nombre_folio:=lpad(cont::text,2,'0');
		nombre_folio:=concat('POLIZAD',anio_new::text,nombre_folio);
		raise notice 'Creando folio: %', nombre_folio;
		insert into keplersc.sqliov (c1,c4,c5,c6,col_sucursal) values(nombre_folio,'0',nombre_tabla,'c1','00');
		commit;
	end loop;

	--Cuentas de taller
	raise notice 'Insertando en kdtallcont';
	insert into keplersc.kdtallcont 
	select c1,c2, lpad(anio_new::text,2,'0'), c4,c5,c6,c7,c8,
	c9,c10,c11,c12,c13,c14,c15,c16,c17,c18
	from keplersc.kdtallcont where c3=lpad(anio_old::text,2,'0') on conflict do nothing;
	commit;

	raise notice 'Insertando en kdivcl';
	insert into keplersc.kdivcl 
	select c1,lpad(anio_new::text,2,'0'),c3,c4,c5,c6,c7,c8,
	c9,c10,c11,c12,c13,c14,c15,c16,c17,c18,
	c19,c20,c21,c22,c23,c24,c25,c26
	from keplersc.kdivcl where c2=lpad(anio_old::text,2,'0') on conflict do nothing;
	commit;

	--Insertar registro kdym
	raise notice 'Insertando en kdym';
	INSERT INTO keplersc.kdym (c1, c2, c3, c4, c5, c6, c7, c8, c9, c10, c11, c12, c13, c14, c15, c16, c17, c18, c19, c20, c21) 
	VALUES(concat('20',anio_new::text), '', '', '', '', '', '', '', '', 'C', 'C', 'C', 'C', 'C', 'C', 'C', 'C', 'C', 'C', 'C', 'C');
	commit;

